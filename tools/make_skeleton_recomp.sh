#!/usr/bin/env bash
# Builds a skeleton of the recompiled game without a ROM: N64Recomp and
# RSPRecomp run on an all-zero 16 MiB image with the project's own config, so
# every function, section, overlay table and hook is generated exactly as for
# the real game, but each body is nothing but NOPs. It contains no game code.
#
#   tools/make_skeleton_recomp.sh [build-dir-of-N64Recomp]
#
# Writes RecompiledFuncs/ and rsp/ts2_aspMain.cpp (both ignored by Git), so the
# whole program compiles and links: for CI, for porting work on a machine
# without the ROM, and for the PS5 cross build. A skeleton build boots no game.
# Never mix it with real output: run tools/run_overlays_pass10.ps1 (and
# RSPRecomp) with your ROM to replace it.
set -euo pipefail
root=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)
bin=${1:-$root/build/N64Recomp}
[[ -x $bin/N64Recomp && -x $bin/RSPRecomp ]] || {
    echo "no N64Recomp/RSPRecomp in $bin: cmake -S tools/N64Recomp -B build/N64Recomp && cmake --build build/N64Recomp" >&2
    exit 2
}
work=$(mktemp -d)
trap 'rm -rf -- "$work"' EXIT
head -c $((16 * 1024 * 1024)) /dev/zero > "$work/zero.z64"
mkdir -p "$work/config" "$work/out" "$work/rsp"
cp "$root/config/toystory2.us.rev0.syms.toml" "$work/config/"
sed -e 's#^rom_file_path = .*#rom_file_path = "../zero.z64"#' \
    -e 's#^output_func_path = .*#output_func_path = "../out"#' \
    "$root/config/toystory2.us.rev0.recomp.toml" > "$work/config/skeleton.recomp.toml"
(cd "$work/config" && "$bin/N64Recomp" skeleton.recomp.toml > "$work/n64recomp.log" 2>&1) ||
    { tail -20 "$work/n64recomp.log" >&2; exit 1; }
sed -e 's#^rom_file_path = .*#rom_file_path = "../zero.z64"#' \
    -e 's#^output_file_path = .*#output_file_path = "./ts2_aspMain.cpp"#' \
    "$root/rsp/ts2_audio.toml" > "$work/rsp/ts2_audio.toml"
(cd "$work/rsp" && "$bin/RSPRecomp" ts2_audio.toml > "$work/rsprecomp.log" 2>&1) ||
    { tail -20 "$work/rsprecomp.log" >&2; exit 1; }
{
    echo "SKELETON: generated by tools/make_skeleton_recomp.sh from an all-zero ROM."
    echo "Every function body is NOPs. This build cannot run the game."
} > "$work/out/SOURCE_PASS.txt"
rm -rf "$root/RecompiledFuncs"
cp -r "$work/out" "$root/RecompiledFuncs"
cp "$work/rsp/ts2_aspMain.cpp" "$root/rsp/ts2_aspMain.cpp"
echo "RecompiledFuncs/: $(ls "$root/RecompiledFuncs"/funcs_*.c | wc -l) files (skeleton); rsp/ts2_aspMain.cpp (skeleton)"
